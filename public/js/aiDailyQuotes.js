export function dailyQuoteIndex(dateString) {
  const input = String(dateString || '').trim();
  let hash = 0;
  for (const char of input) hash = ((hash * 31) + char.charCodeAt(0)) >>> 0;
  return hash % AI_DAILY_QUOTES.length;
}

export function dailyQuoteForDate(dateString) {
  return AI_DAILY_QUOTES[dailyQuoteIndex(dateString)] || AI_DAILY_QUOTES[0];
}
